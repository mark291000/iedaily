/* Builds css/tailwind.css from the classes used in index.html + js/**.
   Usage: npm install && npm run build:css
   Replaces the Tailwind CDN (its runtime JIT re-scanned the DOM on every change -> lag). */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const twDir = process.env.TAILWIND_DIR || path.dirname(require.resolve('tailwindcss/package.json'));
const { compile } = await import(pathToFileURL(path.join(twDir, 'dist/lib.mjs')).href);
const postcss = (await import(process.env.POSTCSS_PATH ? pathToFileURL(process.env.POSTCSS_PATH).href : 'postcss')).default;

function walk(dir, out = []) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p, out); else if (/\.(js|html)$/.test(f.name)) out.push(p);
  }
  return out;
}
const sources = [path.join(root, 'index.html'), ...walk(path.join(root, 'js'))];
const candidates = new Set();
for (const file of sources) {
  const text = fs.readFileSync(file, 'utf8');
  for (const t of text.split(/[\s"'`<>=;{}(),\\]+/)) if (t && t.length < 80) candidates.add(t);
}

const input = fs.readFileSync(path.join(root, 'tools/tailwind.input.css'), 'utf8');
const compiler = await compile(input, {
  base: root,
  loadStylesheet: async (id, base) => {
    const file = id === 'tailwindcss' ? path.join(twDir, 'index.css') : path.resolve(base, id);
    return { path: file, base: path.dirname(file), content: fs.readFileSync(file, 'utf8') };
  },
});
let css = compiler.build([...candidates]);

/* Unwrap @layer so cascade order matches the old CDN (utilities after css/base.css, before css/app.css). */
const ast = postcss.parse(css);
ast.walkAtRules('layer', r => { if (r.nodes) r.replaceWith(r.nodes); else r.remove(); });
css = '/* Generated by tools/build-css.mjs - do not edit by hand */\n' + ast.toString();
fs.writeFileSync(path.join(root, 'css/tailwind.css'), css);
console.log(`css/tailwind.css: ${(css.length / 1024).toFixed(1)} KB from ${candidates.size} tokens`);
